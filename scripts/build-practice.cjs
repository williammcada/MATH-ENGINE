#!/usr/bin/env node
/*
 * Builds the host-facing practice layer (Engine 0.34.0, host-integration-v0.1).
 *  1. src/k7-skills.js  – the K–7 skill baseline wrapped, byte-for-byte, in a loader
 *     function so hosts can run it with a seeded Math object. The baseline is not edited.
 *  2. dist/math-engine-practice.js – one self-contained ESM file (src/practice.js and every
 *     module it requires) for MathQuest's Worker and Math Arcade's server/browser.
 *  3. dist/math-engine-practice.provenance.json – versions and SHA-256 hashes.
 * No third-party bundler is used; requires in src/ are static relative paths.
 */
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..');
const sha = text => crypto.createHash('sha256').update(text).digest('hex');

// 1. K–7 loader
const baselinePath = 'baselines/megaman-v0.7/shared-math.js';
const baseline = fs.readFileSync(path.join(root, baselinePath), 'utf8');
const k7 = `/* GENERATED by scripts/build-practice.cjs from ${baselinePath} (sha256 ${sha(baseline)}).
 * The baseline text between the markers is unedited. Do not edit this file. */
function loadK7Skills(Math) {
/* --- baseline begins --- */
${baseline}
/* --- baseline ends --- */
;return SharedMath;
}
module.exports = { loadK7Skills, baselineSha256: '${sha(baseline)}' };
`;
fs.writeFileSync(path.join(root, 'src/k7-skills.js'), k7);

// 1b. Game-eligible course-bank index (decision D2: auto-checked entries only)
const banks = require('../src/course-banks.js');
const inventoryDir = path.join(root, 'curriculum/course-inventory/v0.1');
const lessonLabels = new Map();
for (const f of fs.readdirSync(inventoryDir).filter(f => f.endsWith('-en.json'))) {
  const inv = JSON.parse(fs.readFileSync(path.join(inventoryDir, f), 'utf8'));
  for (const l of inv.lessons || []) lessonLabels.set(l.id, l.label);
}
const entries = [], excluded = {};
for (const c of banks.catalog) {
  const p = banks.connections.lookup(c.sourceId);
  let item, teacher = false;
  for (let s = 0; s < 200 && !teacher; s++) { item = banks.generate(c.sourceId, { seed: 'catalog-' + s, index: s % 5 }); teacher = item.answer.kind === 'teacher'; }
  if (teacher) { excluded[p.bankId] = (excluded[p.bankId] || 0) + 1; continue; }
  entries.push({ sourceId: c.sourceId, title: c.title, course: c.course, bankId: p.bankId, localGrade: p.localGrade, lessonId: p.lessonId || null, lessonLabel: lessonLabels.get(p.lessonId) || null, topic: p.topic || null, answerKind: item.answer.kind });
}
const courseNames = new Map(entries.map(e => [e.bankId, e.course]));
const courses = banks.connections.coursePlacement.map(c => ({ bankId: c.bankId, course: courseNames.get(c.bankId), localGrade: c.localGrade, placement: c.placement, teacherReviewedExcluded: excluded[c.bankId] || 0 }));
fs.writeFileSync(path.join(root, 'src/practice-index.js'), `/* GENERATED by scripts/build-practice.cjs from course-banks ${banks.version}. Do not edit. */
module.exports = ${JSON.stringify({ bankVersion: banks.version, courses, entries })};
`);

// 2. Bundle
const modules = [], ids = new Map();
function add(file) {
  const abs = path.resolve(file);
  if (ids.has(abs)) return ids.get(abs);
  const id = modules.length; ids.set(abs, id); modules.push(null);
  let src = fs.readFileSync(abs, 'utf8');
  src = src.replace(/require\((['"])(\.[^'"]+)\1\)/g, (m, q, rel) => {
    const target = path.resolve(path.dirname(abs), rel.endsWith('.js') ? rel : rel + '.js');
    return `__req(${add(target)})`;
  });
  if (/\brequire\(/.test(src.replace(/__req\(/g, ''))) throw Error('Unresolved require in ' + file);
  modules[id] = { file: path.relative(root, abs), src };
  return id;
}
const entry = add(path.join(root, 'src/practice.js'));
const body = modules.map((m, i) => `/* ${m.file} */\n${i}: function (module, exports, __req) {\n${m.src}\n}`).join(',\n');
const bundle = `/* Math Engine practice bundle. GENERATED by scripts/build-practice.cjs. Do not edit. */
const __defs = {
${body}
};
const __cache = {};
function __req(id) { if (__cache[id]) return __cache[id].exports; const module = { exports: {} }; __cache[id] = module; __defs[id].call(globalThis, module, module.exports, __req); return module.exports; }
const MathEnginePractice = __req(${entry});
export default MathEnginePractice;
export const { version, bankVersion, k7Version, k7BaselineSha256, catalog, courses, find, generate, nextItem, checkAnswer, evaluate, related, keypadKeys, Practice, freshMath, configError, formatMath, contentHash } = MathEnginePractice;
`;
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/math-engine-practice.js'), bundle);

// 3. Provenance (load the CommonJS source to read versions)
delete require.cache[require.resolve('../src/practice.js')];
const P = require('../src/practice.js');
const prov = {
  module: 'dist/math-engine-practice.js',
  engineVersion: P.version, bankVersion: P.bankVersion, k7Version: P.k7Version,
  bundleSha256: sha(bundle), contentHash: P.contentHash,
  baseline: baselinePath, baselineSha256: sha(baseline),
  sources: modules.map(m => m.file),
  catalog: { total: P.catalog.length, k7: P.catalog.filter(c => c.layer === 'skill').length, bank: P.catalog.filter(c => c.layer === 'bank').length, continuity: P.catalog.filter(c => c.layer === 'continuity').length }
};
fs.writeFileSync(path.join(root, 'dist/math-engine-practice.provenance.json'), JSON.stringify(prov, null, 2) + '\n');
console.log(JSON.stringify({ modules: modules.length, bytes: bundle.length, ...prov.catalog, contentHash: prov.contentHash }));
